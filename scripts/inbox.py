#!/usr/bin/env python3
"""inbox.py — Denis's inbox notes from NeuroBoost, for a session on the PC.

    python scripts/inbox.py pull                    # new + discussed → E:/Projects/docs/inbox/
    python scripts/inbox.py pull --status all       # everything, done and dropped too
    python scripts/inbox.py set 142 143 discussed   # new | discussed | done | dropped
    python scripts/inbox.py retype 142 idea         # inbox | idea | link | feedback | reflection | note

The database is the truth; the markdown is a regenerated copy — edit statuses
here, not in the files. Voice and photos land in media/ (voice → local Whisper
when we go through them). Spec: docs/team/architecture/V003-20261010-arc-inbox-bot.md.

Credentials: INBOX_API_BASE and INBOX_API_TOKEN from the environment, or from
the local memory file below (outside git, like every other key).
"""
import argparse
import json
import os
import sys
import urllib.error
import urllib.parse
import urllib.request
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

ENV_FILE = Path.home() / ".claude/projects/E--Projects-007---Ventures-V003---NeuroBoost/memory/inbox-api.env"
DEFAULT_OUT = Path("E:/Projects/docs/inbox")
TYPES = ["inbox", "idea", "link", "feedback", "reflection", "note"]
STATUSES = ["new", "discussed", "done", "dropped"]
GENERATED = "<!-- generated by scripts/inbox.py -->"
EXT = {"image/jpeg": ".jpg", "audio/ogg": ".ogg", "audio/mpeg": ".mp3", "video/mp4": ".mp4", "application/pdf": ".pdf"}


def config():
    env = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip()
    base = os.environ.get("INBOX_API_BASE") or env.get("INBOX_API_BASE")
    token = os.environ.get("INBOX_API_TOKEN") or env.get("INBOX_API_TOKEN")
    if not base or not token:
        sys.exit(f"❌ INBOX_API_BASE / INBOX_API_TOKEN not set (env or {ENV_FILE})")
    return base.rstrip("/"), token


def call(method, path, body=None, raw=False):
    base, token = config()
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(base + path, data=data, method=method,
                                 headers={"X-Inbox-Token": token, "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            payload = r.read()
    except urllib.error.HTTPError as e:
        sys.exit(f"❌ {method} {path}: {e.code} {e.read()[:200].decode(errors='replace')}")
    except urllib.error.URLError as e:
        sys.exit(f"❌ {method} {path}: {e.reason}")
    return payload if raw else json.loads(payload)["data"]


def when(ts):
    return datetime.fromisoformat(ts.replace("Z", "+00:00")).astimezone().strftime("%Y-%m-%d %H:%M")


def block(n, media_dir):
    head = [f"#{n['id']}", n["type"]]
    if n["projects"]:
        head.append(", ".join(n["projects"]))
    head += [n["status"], when(n["created_at"])]
    if n["via"] == "inline":
        head.append("inline")
    out = ["## " + " · ".join(head), ""]
    src = n.get("source")
    if src:
        who = src.get("name") or src.get("username") or src["kind"]
        out.append(f"> Переслано из: {who} ({src['kind']})" + (f" — {src['url']}" if src.get("url") else ""))
        out.append("")
    if n["text"]:
        out += [n["text"], ""]
    for m in n["media"]:
        if m["stored"]:
            out.append(f"- {m['kind']}: [media/{media_name(n, m)}](media/{media_name(n, m)})")
        else:
            out.append(f"- {m['kind']}: ⚠ не сохранён ({m['size'] / 2**20:.1f} МБ, больше лимита)")
    if n["media"]:
        out.append("")
    return "\n".join(out)


def media_name(n, m):
    ext = EXT.get(m["mime"]) or Path(m["file_name"]).suffix or ".bin"
    return f"{n['id']}-{m['id']}-{m['kind']}{ext}"


def write(path, title, notes, media_dir):
    stamp = datetime.now(timezone.utc).astimezone().strftime("%Y-%m-%d %H:%M")
    body = [f"# {title}", "",
            f"> Сгенерировано `scripts/inbox.py pull` {stamp}. Не править: статус — `inbox.py set <id> <status>`.", ""]
    body += [block(n, media_dir) for n in notes] or ["Пусто."]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(body) + "\n", encoding="utf-8")


def pull(args):
    status = ",".join(STATUSES) if args.status == "all" else args.status
    out = Path(args.out)
    # pull rewrites every .md it finds in --out, so it refuses a folder it did
    # not create: `--out docs` would otherwise wipe a project's documents.
    if out.exists() and any(out.glob("*.md")) and not (
            (out / "INDEX.md").exists() and GENERATED in (out / "INDEX.md").read_text(encoding="utf-8")):
        sys.exit(f"❌ {out} has .md files that inbox.py did not write — choose an empty or inbox folder")
    notes = call("GET", "/api/inbox?" + urllib.parse.urlencode({"status": status}))
    media_dir = out / "media"
    media_dir.mkdir(parents=True, exist_ok=True)
    fetched = 0
    for n in notes:
        for m in n["media"]:
            target = media_dir / media_name(n, m)
            if m["stored"] and not target.exists():
                target.write_bytes(call("GET", f"/api/inbox/media/{m['id']}", raw=True))
                fetched += 1

    by_type, by_project = defaultdict(list), defaultdict(list)
    for n in notes:
        by_type[n["type"]].append(n)
        for p in n["projects"] or ["_bez-proekta"]:
            by_project[p].append(n)
    # Files are a copy of the query: a type or project that emptied out must
    # not keep its stale file.
    for old in list(out.glob("*.md")) + list((out / "by-project").glob("*.md")):
        old.unlink()
    for t, ns in by_type.items():
        write(out / f"{t}.md", f"Inbox — {t}", ns, media_dir)
    for p, ns in by_project.items():
        write(out / "by-project" / f"{p}.md", f"Inbox — проект {p}", ns, media_dir)

    counts = {t: len(by_type.get(t, [])) for t in TYPES}
    index = ["# Inbox", GENERATED, "", f"> `inbox.py pull --status {args.status}` · {len(notes)} заметок", "",
             "| тип | сколько | файл |", "|---|---|---|"]
    index += [f"| {t} | {c} | [{t}.md]({t}.md) |" for t, c in counts.items() if c]
    index += ["", "Проекты: " + " · ".join(f"[{p}](by-project/{p}.md) {len(ns)}" for p, ns in sorted(by_project.items()))]
    (out / "INDEX.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    print(f"✅ {len(notes)} notes → {out} (" + ", ".join(f"{t} {c}" for t, c in counts.items() if c) + f"); media fetched {fetched}")


def set_status(args):
    for i in args.ids:
        n = call("PATCH", f"/api/inbox/{i}", {"status": args.status})
        print(f"✅ #{n['id']} → {n['status']}")


def retype(args):
    n = call("PATCH", f"/api/inbox/{args.id}", {"type": args.type})
    print(f"✅ #{n['id']} → {n['type']}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("pull")
    p.add_argument("--status", default="new,discussed", help="comma list or 'all'")
    p.add_argument("--out", default=str(DEFAULT_OUT))
    p.set_defaults(fn=pull)
    s = sub.add_parser("set")
    s.add_argument("ids", nargs="+", type=int)
    s.add_argument("status", choices=STATUSES)
    s.set_defaults(fn=set_status)
    r = sub.add_parser("retype")
    r.add_argument("id", type=int)
    r.add_argument("type", choices=TYPES)
    r.set_defaults(fn=retype)
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
